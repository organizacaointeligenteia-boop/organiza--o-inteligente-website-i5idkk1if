/**
 * Pure contract types for TypeSafe/Jev Choice primitive.
 * Reference: https://docs.typesafe.ai/primitives/choice
 *
 * Closed enums:
 * - Intent: 'routine' | 'kit' | 'guidance' | 'unknown' | 'restricted'
 * - Topic: 'time' | 'priorities' | 'consistency' | 'general'
 *
 * Isolated brand identifier: 'organizacao-inteligente'
 */

export const JEV_PROJECT_ID = 'organizacao-inteligente' as const
export const JEV_MODEL_ID = 'jev-latest' as const

export const JEV_PROVISIONAL_CONFIDENCE_THRESHOLD = 0.8
export const JEV_PROVISIONAL_THRESHOLD_LABEL = '0.8 (provisório, NÃO calibrado)'

export const JEV_INTENT_OPTIONS = ['routine', 'kit', 'guidance', 'unknown', 'restricted'] as const
export type JevIntentChoice = (typeof JEV_INTENT_OPTIONS)[number]

export const JEV_TOPIC_OPTIONS = ['time', 'priorities', 'consistency', 'general'] as const
export type JevTopicChoice = (typeof JEV_TOPIC_OPTIONS)[number]

/**
 * TypeSafe Choice question specification in request.
 */
export interface TypeSafeChoiceQuestion<K extends string = string> {
  type: 'choice'
  instructions: string
  criteria: Record<K, string>
}

/**
 * Native request body sent to TypeSafe / Jev Choice API.
 * Contains EXATAMENTE state, model, questions (sem project nem metadados extras).
 * Note: 'project' is LOCAL brand-isolation metadata only and must NEVER leak into the native API protocol.
 */
export interface TypeSafeRequestBody {
  state: string
  model: typeof JEV_MODEL_ID
  questions: {
    intent: TypeSafeChoiceQuestion<JevIntentChoice>
    topic: TypeSafeChoiceQuestion<JevTopicChoice>
  }
}

/**
 * Local request envelope wrapping native request with mandatory brand isolation metadata.
 * 'project' is mandatory local metadata and not sent to the remote API.
 */
export interface JevRequestEnvelope {
  project: typeof JEV_PROJECT_ID
  request: TypeSafeRequestBody
}

/**
 * Backwards compatibility alias for JevRequestEnvelope / local request typing.
 * Prefer JevRequestEnvelope for local envelopes and TypeSafeRequestBody for native payloads.
 */
export type JevClassificationRequest = JevRequestEnvelope

/**
 * TypeSafe Choice answer structure.
 */
export interface TypeSafeChoiceAnswer<T extends string = string> {
  type: 'choice'
  choice: T
  confidence: number
  probabilities: Record<T, number>
}

export interface TypeSafeUsage {
  input_tokens: number
  output_tokens: number
}

/**
 * Native raw response body returned by the TypeSafe / Jev service.
 * Does NOT contain 'project' (project is local brand isolation metadata only).
 */
export interface TypeSafeResponseBodyRaw {
  model: string
  answers: {
    intent?: unknown
    topic?: unknown
    [key: string]: unknown
  }
  usage?: TypeSafeUsage
}

/**
 * Local response envelope wrapping native response with mandatory brand isolation metadata.
 * 'project' is mandatory local metadata (never optional) used to verify namespace before evaluation.
 */
export interface JevResponseEnvelope {
  project: typeof JEV_PROJECT_ID
  response: TypeSafeResponseBodyRaw
}

/**
 * Backwards compatibility alias for native raw response body.
 */
export type JevClassificationResponseRaw = TypeSafeResponseBodyRaw

/**
 * Validated choice answer after strict type and mathematical integrity checks.
 */
export interface ValidatedChoiceAnswer<T extends string> {
  choice: T
  confidence: number
  probabilities: Record<T, number>
}

/**
 * High-level triage decision by the local adapter.
 * - 'approved': schema strictly valid, no restricted topic, confidence >= provisional threshold
 * - 'review': schema error, unknown choice, low confidence (< 0.8), or non-restricted ambiguity
 * - 'blocked': restricted clinical / legal / financial topic detected (overrides everything)
 */
export type JevAdapterDecision = 'approved' | 'review' | 'blocked'

/**
 * Normalized outcome produced by the local Jev adapter.
 * NEVER invents certainty: errors fallback to 'review' with intent 'unknown'.
 */
export interface JevAdapterResult {
  decision: JevAdapterDecision
  decisionReason: string
  intent: JevIntentChoice
  topic: JevTopicChoice
  provisionalConfidenceThreshold: number
  isThresholdCalibrated: false
  thresholdDisclaimer: string
  // Note: confidence is purely mathematical from probabilities spread; not a real-world accuracy measure
  rawIntentConfidence: number | null
  rawTopicConfidence: number | null
  // Suggestion mapped to the existing editorial catalog (NO text generated by the model)
  suggestedModelKey: 'priorities' | 'week' | 'steps' | null
  suggestedPath: 'routine' | 'kit' | 'guidance' | null
  restrictedReason?: string
  validationErrors: string[]
}
